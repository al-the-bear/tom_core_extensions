  /// Names a generated class may not take, because the generated code uses
  /// the Dart type of that name.
  static const _reservedClassNames = {
    'Object',
    'String',
    'List',
    'Map',
    'DateTime',
    'Uri',
    'Exception',
    'Future',
    'Duration',
    'Iterable',
    'Set',
    'Type',
    'Function',
    'Null',
  };

  late Map<String, Object?> _schemas;
  late Map<String, String> _classNames;

  /// The Dart source of the client library for [document].
  String generate(Map<String, Object?> document) {
    _schemas = Map.of(
      ((document['components'] as Map?)?['schemas'] as Map?)
              ?.cast<String, Object?>() ??
          const {},
    );
    _classNames = {
      for (final name in _schemas.keys)
        if (_isModel(_schemas[name])) name: _className(name),
    };
    final info = (document['info'] as Map?) ?? const {};
    final title = '${info['title'] ?? clientName}';
    final out = StringBuffer()
      ..writeln('// GENERATED CODE — DO NOT EDIT.')
      ..writeln('//')
      ..writeln('// Generated by tom_core_openapi from the OpenAPI document of')
      ..writeln('// "$title" ${info['version'] ?? ''}.')
      ..writeln(
        regenerateCommand == null
            ? '//'
            : '// Regenerate with: $regenerateCommand',
      )
      ..writeln()
      ..writeln('/// A typed client for "$title", generated from its OpenAPI')
      ..writeln('/// document. It depends on `package:http` only.')
      ..writeln('library;')
      ..writeln()
      ..writeln("import 'dart:convert';")
      ..writeln()
      ..writeln("import 'package:http/http.dart' as http;")
      ..writeln();
    _writeException(out);
    for (final name in _classNames.keys.toList()..sort()) {
      _writeModel(out, name, _schemas[name] as Map);
    }
    _writeClient(out, document);
    return out.toString();
  }

  // ---------------------------------------------------------------------------
  // Names
  // ---------------------------------------------------------------------------

  static String _words(String raw, {required bool upperFirst}) {
    final parts = raw
        .split(RegExp(r'[^A-Za-z0-9]+'))
        .where((p) => p.isNotEmpty)
        .toList();
    if (parts.isEmpty) return upperFirst ? 'Value' : 'value';
    final buffer = StringBuffer();
    for (var i = 0; i < parts.length; i++) {
      final part = parts[i];
      final first = i == 0 && !upperFirst
          ? part[0].toLowerCase()
          : part[0].toUpperCase();
      buffer.write(first + part.substring(1));
    }
    var name = buffer.toString();
    if (RegExp(r'^[0-9]').hasMatch(name)) {
      name = upperFirst ? 'N$name' : 'n$name';
    }
    return name;
  }

  static String _identifier(String raw) {
    final name = _words(raw, upperFirst: false);
    return _keywords.contains(name) ? '${name}Value' : name;
  }

  String _className(String raw) {
    final name = _words(raw, upperFirst: true);
    return _reservedClassNames.contains(name) || name == clientName
        ? '${name}Model'
        : name;
  }

  String get _exceptionName => '${clientName}Exception';

  // ---------------------------------------------------------------------------
  // Schemas → Dart types and conversions
  // ---------------------------------------------------------------------------

  static bool _isModel(Object? schema) =>
      schema is Map &&
      schema['type'] == 'object' &&
      schema['properties'] is Map &&
      (schema['properties'] as Map).isNotEmpty;

  /// The schema [schema] stands for, with a `{type: null}` alternative and a
  /// `"null"` type member removed, and whether either was present.
  (Map, bool) _unwrapNull(Map schema) {
    final anyOf = schema['anyOf'];
    if (anyOf is List && anyOf.length == 2) {
      final rest = anyOf.where((s) => !(s is Map && s['type'] == 'null'));
      if (rest.length == 1) return (rest.single as Map, true);
    }
    final type = schema['type'];
    if (type is List && type.contains('null')) {
      final others = type.where((t) => t != 'null').toList();
      return (
        {...schema, 'type': others.length == 1 ? others.single : others},
        true,
      );
    }
    return (schema, false);
  }

  /// Whether [schema] is a date the generated code holds as a `DateTime`:
  /// a standard `date-time`, or Tom's `@!@`-prefixed `TomDateTime`.
  static bool _isDate(Map schema) =>
      schema['format'] == 'date-time' || schema['x-tom-type'] == 'TomDateTime';

  String? _refName(Map schema) {
    final ref = schema[r'$ref'];
    if (ref is! String || !ref.startsWith('#/components/schemas/')) return null;
    return ref.substring('#/components/schemas/'.length);
  }

  /// The non-nullable Dart type of [schema].
  String _type(Map schema) {
    final (inner, _) = _unwrapNull(schema);
    final ref = _refName(inner);
    if (ref != null) {
      final model = _classNames[ref];
      if (model != null) return model;
      final target = _schemas[ref];
      return target is Map ? _type(target) : 'Object?';
    }
    switch (inner['type']) {
      case 'string':
        return _isDate(inner) ? 'DateTime' : 'String';
      case 'integer':
        return 'int';
      case 'number':
        return 'double';
      case 'boolean':
        return 'bool';
      case 'array':
        final items = inner['items'];
        return 'List<${items is Map ? _fieldType(items) : 'Object?'}>';
      case 'object':
        final values = inner['additionalProperties'];
        return 'Map<String, ${values is Map && values.isNotEmpty ? _fieldType(values) : 'Object?'}>';
      default:
        return 'Object?';
    }
  }

  /// The Dart type of a value described by [schema], nullable where the
  /// schema admits `null`.
  String _fieldType(Map schema, {bool optional = false}) {
    final type = _type(schema);
    if (type.endsWith('?')) return type;
    final (_, nullable) = _unwrapNull(schema);
    return nullable || optional ? '$type?' : type;
  }

  /// An expression decoding the JSON value [source] into [schema]'s type.
  String _decode(Map schema, String source, {bool optional = false}) {
    final (inner, nullable) = _unwrapNull(schema);
    final expression = _decodeNonNull(inner, source);
    if ((nullable || optional) && expression != source) {
      return '$source == null ? null : $expression';
    }
    return expression;
  }

  String _decodeNonNull(Map schema, String source) {
    final ref = _refName(schema);
    if (ref != null) {
      final model = _classNames[ref];
      if (model != null) {
        return '$model.fromJson($source as Map<String, Object?>)';
      }
      final target = _schemas[ref];
      return target is Map ? _decodeNonNull(target, source) : source;
    }
    switch (schema['type']) {
      case 'string':
        if (schema['x-tom-type'] == 'TomDateTime') {
          return "DateTime.parse(($source as String).replaceFirst('@!@', ''))";
        }
        return schema['format'] == 'date-time'
            ? 'DateTime.parse($source as String)'
            : '$source as String';
      case 'integer':
        return '($source as num).toInt()';
      case 'number':
        return '($source as num).toDouble()';
      case 'boolean':
        return '$source as bool';
      case 'array':
        final items = schema['items'];
        return '[for (final e in $source as List) '
            '${items is Map ? _decode(items, 'e') : 'e'}]';
      case 'object':
        final values = schema['additionalProperties'];
        if (values is Map && values.isNotEmpty) {
          return '{for (final e in ($source as Map).entries) '
              'e.key as String: ${_decode(values, 'e.value')}}';
        }
        return '($source as Map).cast<String, Object?>()';
      default:
        return source;
    }
  }

  /// An expression encoding the Dart value [value] of [schema]'s type to JSON.
  String _encode(Map schema, String value, {bool optional = false}) {
    final (inner, nullable) = _unwrapNull(schema);
    final expression = _encodeNonNull(inner, value);
    if (expression == value) return value;
    return nullable || optional
        ? '$value == null ? null : ${_encodeNonNull(inner, '$value!')}'
        : expression;
  }

  String _encodeNonNull(Map schema, String value) {
    final ref = _refName(schema);
    if (ref != null) {
      if (_classNames.containsKey(ref)) return '$value.toJson()';
      final target = _schemas[ref];
      return target is Map ? _encodeNonNull(target, value) : value;
    }
    switch (schema['type']) {
      case 'string':
        if (schema['x-tom-type'] == 'TomDateTime') {
          return "'@!@\${$value.toIso8601String()}'";
        }
        return schema['format'] == 'date-time'
            ? '$value.toUtc().toIso8601String()'
            : value;
      case 'array':
        final items = schema['items'];
        if (items is! Map) return value;
        final element = _encode(items, 'e');
        return element == 'e' ? value : '[for (final e in $value) $element]';
      case 'object':
        final values = schema['additionalProperties'];
        if (values is! Map || values.isEmpty) return value;
        final element = _encode(values, 'e.value');
        return element == 'e.value'
            ? value
            : '{for (final e in $value.entries) e.key: $element}';
      default:
        return value;
    }
  }

  // ---------------------------------------------------------------------------
  // Emitters
  // ---------------------------------------------------------------------------

  static String _docLines(String text, String indent) => [
    for (final line in text.trim().split('\n')) '$indent/// ${line.trim()}',
  ].join('\n').replaceAll(RegExp(r' +$', multiLine: true), '');

  void _writeException(StringBuffer out) {
    out
      ..writeln('/// A call that did not succeed: the HTTP [statusCode], the')
      ..writeln(
        '/// raw [body], the response [headers] — `retry-after` on a 429',
      )
      ..writeln(
        '/// — and the error envelope\'s [errorKey] when the server sent',
      )
      ..writeln('/// one.')
      ..writeln('class $_exceptionName implements Exception {')
      ..writeln('  /// The HTTP status code.')
      ..writeln('  final int statusCode;')
      ..writeln()
      ..writeln('  /// The response body as received.')
      ..writeln('  final String body;')
      ..writeln()
      ..writeln('  /// The error envelope\'s `errorKey`, or `null`.')
      ..writeln('  final String? errorKey;')
      ..writeln()
      ..writeln('  /// The response headers, lower-cased by name.')
      ..writeln('  final Map<String, String> headers;')
      ..writeln()
      ..writeln('  /// How long a `429` asks the caller to wait, or `null`.')
      ..writeln('  Duration? get retryAfter {')
      ..writeln(
        "    final seconds = int.tryParse(headers['retry-after'] ?? '');",
      )
      ..writeln(
        '    return seconds == null ? null : Duration(seconds: seconds);',
      )
      ..writeln('  }')
      ..writeln()
      ..writeln(
        '  /// A failure with [statusCode], [body], [errorKey] and [headers].',
      )
      ..writeln(
        '  $_exceptionName(this.statusCode, this.body, this.errorKey, '
        '[this.headers = const {}]);',
      )
      ..writeln()
      ..writeln('  /// The failure [response] reports.')
      ..writeln('  factory $_exceptionName.of(http.Response response) {')
      ..writeln('    String? key;')
      ..writeln('    try {')
      ..writeln('      final decoded = jsonDecode(response.body);')
      ..writeln("      if (decoded is Map && decoded['errorKey'] is String) {")
      ..writeln("        key = decoded['errorKey'] as String;")
      ..writeln('      }')
      ..writeln('    } on FormatException {')
      ..writeln('      key = null;')
      ..writeln('    }')
      ..writeln(
        '    return $_exceptionName(response.statusCode, response.body, key, '
        'response.headers);',
      )
      ..writeln('  }')
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        "  String toString() => '$_exceptionName(\$statusCode\${errorKey == null ? '' : ', \$errorKey'})';",
      )
      ..writeln('}')
      ..writeln();
  }

  void _writeModel(StringBuffer out, String schemaName, Map schema) {
    final name = _classNames[schemaName]!;
    final properties = (schema['properties'] as Map).cast<String, Object?>();
    final required = {...?(schema['required'] as List?)?.cast<String>()};
    final fields = [
      for (final entry in properties.entries)
        (
          json: entry.key,
          dart: _identifier(entry.key),
          schema: entry.value as Map,
          optional: !required.contains(entry.key),
        ),
    ];
    final description = schema['description'];
    out
      ..writeln(
        description is String
            ? _docLines(description, '')
            : '/// The `$schemaName` schema.',
      )
      ..writeln('class $name {');
    for (final f in fields) {
      out
        ..writeln("  /// The `${f.json}` member.")
        ..writeln('  ${_fieldType(f.schema, optional: f.optional)} ${f.dart};')
        ..writeln();
    }
    out
      ..writeln('  /// A `$schemaName` with the given members.')
      ..writeln('  $name({');
    for (final f in fields) {
      out.writeln(
        f.optional ? '    this.${f.dart},' : '    required this.${f.dart},',
      );
    }
    out
      ..writeln('  });')
      ..writeln()
      ..writeln('  /// Decodes a `$schemaName` from its JSON object.')
      ..writeln(
        '  factory $name.fromJson(Map<String, Object?> json) => $name(',
      );
    for (final f in fields) {
      out.writeln(
        "    ${f.dart}: ${_decode(f.schema, "json['${f.json}']", optional: f.optional)},",
      );
    }
    out
      ..writeln('  );')
      ..writeln()
      ..writeln('  /// This value as its JSON object.')
      ..writeln('  Map<String, Object?> toJson() => {');
    for (final f in fields) {
      if (!f.optional) {
        out.writeln("    '${f.json}': ${_encode(f.schema, f.dart)},");
        continue;
      }
      // An absent optional member is left out rather than sent as null: a
      // member the schema does not let be null may still be optional.
      final (inner, _) = _unwrapNull(f.schema);
      final encoded = _encodeNonNull(inner, '${f.dart}!');
      final value = encoded == '${f.dart}!' ? f.dart : encoded;
      out.writeln("    if (${f.dart} != null) '${f.json}': $value,");
    }
    out
      ..writeln('  };')
      ..writeln('}')
      ..writeln();
  }

  void _writeClient(StringBuffer out, Map<String, Object?> document) {
    out
      ..writeln('/// Calls the operations of the API, one method each.')
      ..writeln('///')
      ..writeln('/// Operations that require authentication send [bearerToken]')
      ..writeln('/// when it is set, else [apiKey] as `X-API-Key`; public')
      ..writeln('/// operations send neither.')
      ..writeln('class $clientName {')
      ..writeln('  /// The server every call is addressed to.')
      ..writeln('  final Uri baseUri;')
      ..writeln()
      ..writeln('  /// The bearer token sent to operations that require one.')
      ..writeln('  String? bearerToken;')
      ..writeln()
      ..writeln(
        '  /// The API key sent to operations that require authentication',
      )
      ..writeln('  /// when no [bearerToken] is set.')
      ..writeln('  String? apiKey;')
      ..writeln()
      ..writeln('  final http.Client _http;')
      ..writeln()
      ..writeln('  /// A client of the server at [baseUri], over [httpClient]')
      ..writeln('  /// (a new one when omitted).')
      ..writeln(
        '  $clientName(this.baseUri, {http.Client? httpClient, this.bearerToken, this.apiKey})',
      )
      ..writeln('    : _http = httpClient ?? http.Client();')
      ..writeln()
      ..writeln('  /// Closes the underlying HTTP client.')
      ..writeln('  void close() => _http.close();')
      ..writeln();
    final paths = ((document['paths'] as Map?) ?? const {})
        .cast<String, Object?>();
    final used = <String>{'close'};
    for (final path in paths.keys) {
      final operations = (paths[path] as Map).cast<String, Object?>();
      for (final method in operations.keys) {
        _writeOperation(
          out,
          path,
          method,
          (operations[method] as Map).cast<String, Object?>(),
          used,
        );
      }
    }
    _writeSend(out);
    out.writeln('}');
  }

  void _writeOperation(
    StringBuffer out,
    String path,
    String method,
    Map<String, Object?> operation,
    Set<String> used,
  ) {
    var name = _identifier('${operation['operationId'] ?? '$method $path'}');
    while (!used.add(name)) {
      name = '${name}Again';
    }
    final parameters = [
      for (final p in (operation['parameters'] as List?) ?? const [])
        (p as Map).cast<String, Object?>(),
    ];
    final arguments = <String>[];
    final pathValues = <String, String>{};
    final queryValues = <String, String>{};
    final names = <String>{};
    for (final parameter in parameters) {
      final schema = (parameter['schema'] as Map?) ?? const {};
      final required = parameter['required'] == true;
      var dart = _identifier('${parameter['name']}');
      while (!names.add(dart)) {
        dart = '${dart}Value';
      }
      arguments.add(
        required
            ? 'required ${_fieldType(schema)} $dart'
            : '${_fieldType(schema, optional: true)} $dart',
      );
      final asText = _type(schema) == 'String'
          ? dart
          : '$dart${required ? '' : '?'}.toString()';
      if (parameter['in'] == 'path') {
        pathValues['${parameter['name']}'] = asText;
      } else if (parameter['in'] == 'query') {
        queryValues['${parameter['name']}'] = asText;
      }
    }

    String? bodyKind;
    Map? bodySchema;
    String? contentType;
    final requestBody = operation['requestBody'];
    var bodyRequired = false;
    if (requestBody is Map) {
      bodyRequired = requestBody['required'] == true;
      final content = (requestBody['content'] as Map?) ?? const {};
      if (content.containsKey('multipart/form-data')) {
        bodyKind = 'multipart';
        arguments
          ..add('Map<String, String> fields = const {}')
          ..add('List<http.MultipartFile> files = const []');
      } else if (content.isNotEmpty) {
        contentType = content.keys.first as String;
        final media = content[contentType];
        bodySchema = media is Map ? media['schema'] as Map? : null;
        bodyKind = bodySchema != null && contentType.contains('json')
            ? 'json'
            : 'raw';
        final type = bodyKind == 'json'
            ? _fieldType(bodySchema!, optional: !bodyRequired)
            : 'Object?';
        arguments.add(
          bodyRequired && bodyKind == 'json'
              ? 'required $type body'
              : '$type body',
        );
      }
    }

    final responses = ((operation['responses'] as Map?) ?? const {})
        .cast<String, Object?>();
    final success = responses['200'];
    String returns;
    String? decoder;
    if (success is Map && success['content'] is Map) {
      final content = (success['content'] as Map).cast<String, Object?>();
      final json = content['application/json'];
      final schema = json is Map ? json['schema'] : null;
      if (schema is Map) {
        returns = _fieldType(schema);
        decoder = _decode(schema, 'decoded');
      } else {
        returns = 'http.Response';
      }
    } else if (responses.containsKey('200')) {
      returns = 'void';
    } else {
      returns = 'http.Response';
    }

    final secured = (operation['security'] as List?)?.isNotEmpty ?? true;
    final description = operation['description'];
    out.writeln(
      _docLines(
        '`${method.toUpperCase()} $path`'
            '${description is String ? '\n\n$description' : ''}',
        '  ',
      ),
    );
    out.writeln(
      '  Future<$returns> $name(${arguments.isEmpty ? '' : '{${arguments.join(', ')}}'}) async {',
    );
    var pathExpression = path;
    for (final entry in pathValues.entries) {
      pathExpression = pathExpression.replaceAll(
        '{${entry.key}}',
        '\${Uri.encodeComponent(${entry.value})}',
      );
    }
    out.writeln(
      returns == 'void'
          ? '    await _send('
          : '    final response = await _send(',
    );
    out.writeln("      '${method.toUpperCase()}',");
    out.writeln("      '$pathExpression',");
    if (queryValues.isNotEmpty) {
      out.writeln('      query: {');
      for (final entry in queryValues.entries) {
        out.writeln("        '${entry.key}': ${entry.value},");
      }
      out.writeln('      },');
    }
    if (bodyKind == 'json') {
      out.writeln(
        "      body: ${bodyRequired ? '' : 'body == null ? null : '}"
        'jsonEncode(${_encode(bodySchema!, 'body')}),',
      );
      out.writeln("      contentType: '$contentType',");
    } else if (bodyKind == 'raw') {
      out.writeln('      body: body,');
      out.writeln("      contentType: '$contentType',");
    } else if (bodyKind == 'multipart') {
      out.writeln('      fields: fields,');
      out.writeln('      files: files,');
    }
    out.writeln('      authenticated: $secured,');
    out.writeln('    );');
    if (returns == 'http.Response') {
      out.writeln('    return response;');
    } else if (returns != 'void') {
      out
        ..writeln(
          '    final Object? decoded = jsonDecode(utf8.decode(response.bodyBytes));',
        )
        ..writeln('    return $decoder;');
    }
    out
      ..writeln('  }')
      ..writeln();
  }

  void _writeSend(StringBuffer out) {
    out
      ..writeln('  /// Sends one request and throws [$_exceptionName] for any')
      ..writeln('  /// status outside 2xx and 3xx.')
      ..writeln('  Future<http.Response> _send(')
      ..writeln('    String method,')
      ..writeln('    String path, {')
      ..writeln('    Map<String, String?> query = const {},')
      ..writeln('    Object? body,')
      ..writeln('    String? contentType,')
      ..writeln('    Map<String, String>? fields,')
      ..writeln('    List<http.MultipartFile>? files,')
      ..writeln('    required bool authenticated,')
      ..writeln('  }) async {')
      ..writeln('    final base = baseUri.path.endsWith(\'/\')')
      ..writeln('        ? baseUri.path.substring(0, baseUri.path.length - 1)')
      ..writeln('        : baseUri.path;')
      ..writeln('    final present = {')
      ..writeln('      for (final e in query.entries)')
      ..writeln('        if (e.value != null) e.key: e.value!,')
      ..writeln('    };')
      ..writeln('    final uri = baseUri.replace(')
      ..writeln('      path: \'\$base\$path\',')
      ..writeln('      queryParameters: present.isEmpty ? null : present,')
      ..writeln('    );')
      ..writeln('    final headers = <String, String>{')
      ..writeln("      'accept': 'application/json',")
      ..writeln('      if (authenticated && bearerToken != null)')
      ..writeln("        'authorization': 'Bearer \$bearerToken'")
      ..writeln('      else if (authenticated && apiKey != null)')
      ..writeln("        'x-api-key': apiKey!,")
      ..writeln('    };')
      ..writeln('    final http.BaseRequest request;')
      ..writeln('    if (fields != null || files != null) {')
      ..writeln('      request = http.MultipartRequest(method, uri)')
      ..writeln('        ..fields.addAll(fields ?? const {})')
      ..writeln('        ..files.addAll(files ?? const []);')
      ..writeln('    } else {')
      ..writeln('      final plain = http.Request(method, uri);')
      ..writeln('      if (body is String) {')
      ..writeln('        plain.body = body;')
      ..writeln('      } else if (body is List<int>) {')
      ..writeln('        plain.bodyBytes = body;')
      ..writeln('      } else if (body != null) {')
      ..writeln('        plain.body = jsonEncode(body);')
      ..writeln('      }')
      ..writeln('      request = plain;')
      ..writeln('    }')
      ..writeln('    request.headers.addAll(headers);')
      ..writeln('    if (contentType != null && body != null) {')
      ..writeln("      request.headers['content-type'] = contentType;")
      ..writeln('    }')
      ..writeln(
        '    final response = await http.Response.fromStream(await _http.send(request));',
      )
      ..writeln(
        '    if (response.statusCode < 200 || response.statusCode >= 400) {',
      )
      ..writeln('      throw $_exceptionName.of(response);')
      ..writeln('    }')
      ..writeln('    return response;')
      ..writeln('  }');
  }
