/// Generates a typed Dart client from an OpenAPI 3.1 document.
///
/// The generated library depends on `package:http` and nothing else — no Tom
/// package, no reflection — so any Dart program can call a Tom server with it,
/// and a Tom client can call a server it does not share a contracts package
/// with. It reads the document only, never the server, which is what lets the
/// same generator serve any OpenAPI 3.1 document of the shapes Tom writes.
///
/// What is generated:
///
///  * one class per object schema in `components.schemas`, with a constructor,
///    `fromJson` and `toJson`; a schema without declared properties (an
///    `x-tom-opaque` type) is a `Map<String, Object?>` rather than a class;
///  * one client class with a method per operation, named after its
///    `operationId`, taking path and query parameters as named arguments and
///    the request body as `body`;
///  * one exception type carrying the status code, the body and — when the
///    server answered with the framework's error envelope — its `errorKey`.
///
/// Tom's one wire convention a plain OpenAPI string cannot express — an
/// observable `TomDateTime` member travelling as `@!@<ISO-8601>`, marked
/// `x-tom-type: TomDateTime` in the schema — is decoded to and encoded from a
/// `DateTime`; any other generator sees a string, which is also correct.
///
/// A response the document types (`application/json` with a schema) is
/// decoded into the declared type; a response it leaves untyped is returned as
/// the raw `http.Response`; an operation answering with no body returns
/// `Future<void>`.
library;

/// Generates the client library for a document.
class TomOpenApiDartClientGenerator {
  /// The name of the generated client class.
  final String clientName;

  /// The command that regenerates the file, stated in its header.
  final String? regenerateCommand;

  /// A generator producing a client class named [clientName].
  TomOpenApiDartClientGenerator({
    required this.clientName,
    this.regenerateCommand,
  });

